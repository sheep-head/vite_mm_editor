export function getCatalogByPage(page) {
  const items = COMMAND_CATALOG.filter((c) => c.page === page)
  const groups = []
  const map = new Map()
  for (const c of items) {
    if (!map.has(c.group)) {
      const g = { name: c.group, items: [] }
      map.set(c.group, g)
      groups.push(g)
    }
    map.get(c.group).items.push(c)
  }
  return groups
}

export function findCatalogEntry(code, page) {
  if (page != null) {
    const byPage = COMMAND_CATALOG.find((c) => c.code === code && c.page === page)
    if (byPage) return byPage
  }
  return COMMAND_CATALOG.find((c) => c.code === code) || null
}
