/** RPG Maker MV/MZ 插件头注释与 plugins.js */

export function parsePluginSource(src) {
  const text = String(src || '')
  const main = text.match(/\/\*:([\s\S]*?)\*\//)
  const meta = main ? parseLines(commentLines(main[1])) : emptyMeta()
  meta.structs = {}
  const re = /\/\*~struct~([^:*\r\n]+):([\s\S]*?)\*\//g
  let m
  while ((m = re.exec(text))) {
    const name = m[1].trim()
    meta.structs[name] = parseLines(commentLines(m[2])).params
  }
  return meta
}

export function parsePluginsJs(text) {
  const src = String(text || '')
  const m = src.match(/var\s+\$plugins\s*=\s*(\[[\s\S]*\])\s*;?/)
  if (!m) return []
  try {
    const arr = JSON.parse(m[1])
    return Array.isArray(arr) ? arr : []
  } catch (e) {
    return []
  }
}

export function stringifyPluginsJs(list) {
  const lines = (list || []).map((p) => {
    const parameters = p.parameters && typeof p.parameters === 'object' ? p.parameters : {}
    return JSON.stringify({
      name: p.name || '',
      status: !!p.status,
      description: p.description || '',
      parameters,
    })
  })
  return (
    '// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n[\n' +
    lines.join(',\n') +
    '\n];\n'
  )
}

export function mzSupportNote(name, meta) {
  const target = String((meta && meta.target) || '')
  const parts = target.toUpperCase().split(/[\s,;/]+/).filter(Boolean)
  if (parts.includes('MZ')) return ''
  return `插件“${name}”不一定支持RPG制作大师MZ。`
}

export function buildParamTree(params) {
  const nodes = (params || []).map((p) => ({ ...p, children: [] }))
  const byName = new Map(nodes.map((n) => [n.name, n]))
  const roots = []
  nodes.forEach((n) => {
    const parent = n.parent && byName.get(n.parent)
    if (parent && parent !== n) parent.children.push(n)
    else roots.push(n)
  })
  return roots
}

export function readJsonObject(raw) {
  try {
    const o = JSON.parse(raw || '{}')
    if (o && typeof o === 'object' && !Array.isArray(o)) return o
  } catch (e) {
    /* ignore */
  }
  return {}
}

export function readJsonArray(raw) {
  try {
    const a = JSON.parse(raw || '[]')
    if (Array.isArray(a)) return a.map((x) => (x == null ? '' : String(x)))
  } catch (e) {
    /* ignore */
  }
  return []
}

export function structFieldDefaults(fields) {
  const o = {}
  ;(fields || []).forEach((f) => {
    if (!f || f.group) return
    o[f.name] = f.default != null ? String(f.default) : ''
  })
  return o
}

function emptyMeta() {
  return { plugindesc: '', author: '', target: '', help: '', params: [], structs: {} }
}

function commentLines(body) {
  return String(body || '')
    .split(/\r?\n/)
    .map((line) => {
      const m = line.match(/^\s*\*\s?(.*)$/)
      return m ? m[1] : null
    })
    .filter((line) => line != null)
}

function parseLines(lines) {
  const meta = emptyMeta()
  let current = null
  let mode = ''
  let lastOption = null
  lines.forEach((line) => {
    const tag = line.match(/^@(\w+)(?:\s+([\s\S]*))?$/)
    if (tag) {
      const name = tag[1]
      const rest = (tag[2] || '').trim()
      if (name === 'plugindesc') {
        meta.plugindesc = rest
        mode = 'plugindesc'
        current = null
      } else if (name === 'author') {
        meta.author = rest
        mode = ''
      } else if (name === 'target') {
        meta.target = rest
        mode = ''
      } else if (name === 'help') {
        mode = 'help'
        meta.help = rest ? rest + '\n' : ''
        current = null
      } else if (name === 'param') {
        current = {
          name: rest,
          text: rest,
          desc: '',
          type: '',
          default: '',
          min: '',
          max: '',
          parent: '',
          dir: '',
          on: '',
          off: '',
          options: [],
        }
        meta.params.push(current)
        mode = 'param'
        lastOption = null
      } else if (current && name === 'text') {
        current.text = rest
        mode = 'param'
      } else if (current && name === 'desc') {
        current.desc = rest
        mode = 'desc'
      } else if (current && name === 'type') {
        current.type = rest
        mode = 'param'
      } else if (current && name === 'default') {
        current.default = rest
        mode = 'param'
      } else if (current && name === 'min') {
        current.min = rest
      } else if (current && name === 'max') {
        current.max = rest
      } else if (current && name === 'parent') {
        current.parent = rest
      } else if (current && name === 'dir') {
        current.dir = rest
      } else if (current && name === 'on') {
        current.on = rest
      } else if (current && name === 'off') {
        current.off = rest
      } else if (current && name === 'option') {
        lastOption = { label: rest, value: rest }
        current.options.push(lastOption)
        mode = 'param'
      } else if (current && name === 'value' && lastOption) {
        lastOption.value = rest
      } else {
        mode = ''
      }
      return
    }
    if (mode === 'help') meta.help += line + '\n'
    else if (mode === 'desc' && current) current.desc += (current.desc ? '\n' : '') + line
    else if (mode === 'plugindesc' && line.trim()) meta.plugindesc += ' ' + line.trim()
  })
  meta.help = meta.help.replace(/\s+$/, '')
  meta.params.forEach((p) => {
    p.typeInfo = classifyParam(p)
    p.group = p.typeInfo.kind === 'group'
  })
  return meta
}

function classifyParam(p) {
  const type = String(p.type || '').trim()
  if (!type) {
    const label = p.text || p.name || ''
    const separator = /^-{2,}.*-{2,}$/.test(p.name || '') || /^-{2,}.*-{2,}$/.test(label)
    const bare = !p.default && !p.desc && !p.options.length && !p.min && !p.max && !p.on && !p.off
    if (separator || bare) return { kind: 'group', array: false, struct: '' }
    return { kind: 'string', array: false, struct: '' }
  }
  const array = type.endsWith('[]')
  const base = array ? type.slice(0, -2).trim() : type
  const struct = base.match(/^struct<(.+)>$/i)
  if (struct) return { kind: 'struct', array, struct: struct[1].trim() }
  return { kind: base.toLowerCase(), array, struct: '' }
}
